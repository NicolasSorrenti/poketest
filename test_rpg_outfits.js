'use strict';
const assert=require('node:assert/strict');
const {select,sources,safeImage}=require('./rpg_outfits');
const base='/rpg-assets/characters/laca/neutral.webp',casual='/rpg-assets/characters/laca/outfits/casual/neutral.webp',red='/rpg-assets/characters/laca/outfits/lifeguard/neutral.webp',smile='/rpg-assets/characters/laca/outfits/lifeguard/happy.webp';
const art={portrait:base,outfits:{default:'casual',variants:{casual:{portrait:casual},lifeguard:{portrait:red,expressions:{happy:smile}}},rules:[{outfit:'lifeguard',locations:['park'],slots:[0,1],weekdays:[0,1,2,3,4]}],sceneOverrides:{laca_evening_rescue:'lifeguard'}}};
assert.equal(select(art.outfits,{location:'park',slot:0,day:1}).key,'lifeguard');
assert.equal(select(art.outfits,{location:'park',slot:1,day:2}).key,'lifeguard');
assert.equal(select(art.outfits,{location:'park',slot:2,day:2}).key,'casual');
assert.equal(select(art.outfits,{location:'shop',slot:0,day:2}).key,'casual');
assert.equal(select(art.outfits,{location:'park',slot:0,day:6}).key,'casual');
assert.equal(select(art.outfits,{location:'cafe',slot:2,day:6,sceneId:'laca_evening_rescue'}).key,'lifeguard');
assert.deepEqual(sources(art,{location:'park',slot:0,day:1},'happy',{base}),[smile,red,base]);
assert.deepEqual(sources(art,{location:'park',slot:0,day:1},'surprised',{base}),[red,base]);
assert.deepEqual(sources(art,{location:'shop',slot:0,day:2},'happy',{base}),[casual,base]);
assert.deepEqual(sources({portrait:base},{},'happy',{base,legacy:'/rpg-assets/characters/laca/vn-expressions/happy.webp'}),['/rpg-assets/characters/laca/vn-expressions/happy.webp',base]);
assert.deepEqual(sources(null,{},'neutral',{base}),[base]);
assert.equal(select({default:'missing',variants:{}},{}),null);
assert.equal(safeImage('/rpg-assets/characters/laca/outfits/red.png'),true);
assert.equal(safeImage('https://other/a.png'),false);
assert.equal(safeImage('/rpg-assets/../secret.png'),false);
console.log('RPG outfit selection, scene override, expression fallback and image security passed.');
