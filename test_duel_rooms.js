'use strict';
const assert=require('node:assert/strict');
const {RoomCoordinator}=require('./duel_rooms');
const {publicView,validateCommand}=require('./duel_protocol');
const fixture=()=>({turn:0,round:1,phase:'game',over:false,message:[],players:[{name:'Host',hand:['hidden-A'],deck:['deck-A'],prizes:['prize-A'],active:null,bench:[],discard:[]},{name:'Guest',hand:['hidden-B'],deck:['deck-B'],prizes:['prize-B'],active:null,bench:[],discard:[]}]});
const rooms=new RoomCoordinator({createGame:fixture,applyCommand:(game,side,command)=>{if(command.type==='end_turn'){game.turn=1-side;return {ok:true}}return {ok:false,error:'unsupported'}}});
const a=rooms.create(),b=rooms.join(a.code.toLowerCase());
assert.match(a.code,/^[A-HJ-NP-Z2-9]{6}$/);
assert.equal(a.player,0);assert.equal(b.player,1);assert.notEqual(a.token,b.token);
assert.throws(()=>rooms.join(a.code),/full/);
assert.throws(()=>rooms.view(a.code,'bogus'),/Unauthorized/);
assert.throws(()=>rooms.start(a.code,b.token),/Only host/);
rooms.start(a.code,a.token);
let va=rooms.view(a.code,a.token),vb=rooms.view(a.code,b.token);
assert.deepEqual(va.view.players[0].hand,['hidden-A']);
assert.equal(va.view.players[1].hand,undefined);
assert.deepEqual(vb.view.players[1].hand,['hidden-B']);
assert.equal(vb.view.players[0].hand,undefined);
assert.equal(JSON.stringify(va).includes('deck-A'),false);
assert.equal(JSON.stringify(va).includes('prize-A'),false);
assert.throws(()=>rooms.dispatch(a.code,b.token,{type:'end_turn'},va.revision),/Not your turn/);
assert.throws(()=>rooms.dispatch(a.code,a.token,{type:'invalid'},va.revision),/Unknown/);
const result=rooms.dispatch(a.code,a.token,{type:'end_turn'},va.revision);
assert.equal(result.view.turn,1);
assert.throws(()=>rooms.dispatch(a.code,a.token,{type:'end_turn'},va.revision),/Stale/);
assert.throws(()=>rooms.dispatch(a.code,a.token,{type:'end_turn'},result.revision),/Not your turn/);
const response=rooms.dispatch(a.code,b.token,{type:'end_turn'},result.revision);
assert.equal(response.view.turn,0);
assert.throws(()=>validateCommand({type:'end_turn',payload:[]}),/payload/);
assert.throws(()=>publicView(fixture(),2),/viewer/);
const isolated=fixture();isolated.players[0].active={id:'card',damage:0};isolated.players[0].bench=[{id:'bench',damage:0}];
const projection=publicView(isolated,0);projection.players[0].active.damage=500;projection.players[0].bench[0].damage=500;projection.players[0].discard.push('hack');
assert.equal(isolated.players[0].active.damage,0);assert.equal(isolated.players[0].bench[0].damage,0);assert.equal(isolated.players[0].discard.length,0);
console.log('PASS: code-based rooms, authentication, isolation, private views, revisions, turn validation');
