'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {ClassicOnlineService}=require('./classic_online_service');
let now=1_000_000;
const service=new ClassicOnlineService({now:()=>now});
const host=service.create({deck:'brushfire',name:'Host'});
const guest=service.join({code:host.code,deck:'blackout',name:'Guest'});
const code=host.code;
let state=service.state(code,host.token);
state=service.ready(code,host.token,{revision:state.revision,ready:true});
state=service.ready(code,guest.token,{revision:state.revision,ready:true});
state=service.start(code,host.token,{revision:state.revision});
const spectator=service.watch({code,name:'Viewer'});
const originalRevision=state.revision;
const png='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScL/nwAAAABJRU5ErkJggg==';
assert.throws(()=>service.setPlaymat(code,spectator.token,{id:'aurora'}),/Spectators/);
assert.throws(()=>service.setPlaymat(code,'bad-token',{id:'aurora'}),/Unauthorized/);
assert.throws(()=>service.getPlaymat(code,'bad-token',0),/Unauthorized/);
assert.throws(()=>service.setPlaymat(code,host.token,{id:'invalid'}),/Invalid playmat/);
assert.throws(()=>service.setPlaymat(code,host.token,{id:'custom',image:'https://example.com/mat.png'}),/Invalid playmat image/);
assert.throws(()=>service.setPlaymat(code,host.token,{id:'custom',image:'data:image/svg+xml;base64,PHN2Zz4='}),/Invalid playmat image/);
assert.throws(()=>service.setPlaymat(code,host.token,{id:'custom',image:'data:image/png;base64,'+Buffer.alloc(165000).toString('base64')}),/too large|oversized/);
const first=service.setPlaymat(code,host.token,{id:'custom',image:png});
assert.equal(first.revision,originalRevision,'Cosmetic changes must not invalidate card actions');
assert.equal(first.playmats[0].id,'custom');
assert.equal(first.playmats[0].cooldownUntil,now+120000);
assert.equal(first.playmats[1],null);
const other=service.state(code,guest.token);
assert.equal(other.playmats[0].id,'custom');
assert.equal(other.playmats[0].version,1);
assert.equal(other.revision,originalRevision);
assert(!JSON.stringify(other).includes('iVBOR'),'Image bytes must NOT travel in polling responses');
assert.equal(service.getPlaymat(code,guest.token,0).image,png,'Opponent can fetch the image');
assert.equal(service.getPlaymat(code,spectator.token,0).image,png,'Spectator can see the room mat');
assert.equal(service.getPlaymat(code,host.token,1).image,null);
assert.throws(()=>service.getPlaymat(code,guest.token,4),/Invalid player side/);
assert.throws(()=>service.setPlaymat(code,host.token,{id:'heritage'}),/cooldown/i);
now+=119999;
assert.throws(()=>service.setPlaymat(code,host.token,{id:'arcade'}),/cooldown/i);
const guestFirst=service.setPlaymat(code,guest.token,{id:'arcade'});
assert.equal(guestFirst.playmats[1].id,'arcade','Second player has independent cooldown');
now+=1;
const next=service.setPlaymat(code,host.token,{id:'heritage'});
assert.equal(next.revision,originalRevision);
assert.equal(next.playmats[0].version,2);
assert.equal(next.playmats[0].id,'heritage');
assert.equal(service.getPlaymat(code,guest.token,0).image,null,'Old image must not linger');
assert.throws(()=>service.setPlaymat(code,guest.token,{id:'aurora'}),/cooldown/i);
assert.equal(service.state(code,host.token).cube,false,'Regular online duels allow both players to customize mats');
now+=120000;
service.findRoom(code).cube=true;
assert.equal(service.state(code,host.token).cube,true,'Cube status is authoritative');
assert.throws(()=>service.setPlaymat(code,host.token,{id:'aurora'}),/Only the account owner/,'A Cube host without account authorization cannot change mats');
assert.throws(()=>service.setPlaymat(code,guest.token,{id:'custom',image:png}),/Only the account owner/,'A Cube guest without account authorization cannot upload mats');
assert.throws(()=>service.setPlaymat(code,spectator.token,{id:'heritage'},true),/Spectators/,'Verified accounts cannot bypass spectator restrictions');
const ownerChange=service.setPlaymat(code,guest.token,{id:'heritage'},true);
assert.equal(ownerChange.playmats[1].id,'heritage','Verified owner can change Cube mats from either player seat');
assert.equal(ownerChange.revision,originalRevision,'Cube mat updates must not affect gameplay revision');
const html=fs.readFileSync(__dirname+'/online.html','utf8');
const js=fs.readFileSync(__dirname+'/online.js','utf8');
const server=fs.readFileSync(__dirname+'/server.js','utf8');
const style=fs.readFileSync(__dirname+'/online_playmats.css','utf8');
new vm.Script(js,{filename:'online.js'});
for(const id of ['onlinePlaymatSelect','onlinePlaymatControl','onlinePlaymatStatus'])
 assert(html.includes('id="'+id+'"'),id+' must appear in the online page');
assert.match(server,/online\.setPlaymat/);
assert.match(server,/online\.getPlaymat/);
assert(server.includes("CUBE_PLAYMAT_OWNER_EMAIL='nicolassorrenti2@gmail.com'"),'Server enforces the requested owner account');
assert(server.includes("'/auth/v1/user'"),'Server checks the Supabase user identity');
assert(server.includes('email_confirmed_at'),'Owner email must be verified');
assert(server.includes('online.setPlaymat(body.code,token,body,canEdit)'),'Server passes verified account permission');
assert(js.includes('checkCubeMatPermission('),'Cube permission gates UI controls');
assert(js.includes('cubeMatBearer('),'Authorized Cube owner authenticates changes');
assert(js.includes('online-mat-studio'),'Studio link must be hidden in non-owner Cube matches');
assert.match(js,/updateDisplayedMats\(state\)/,'Room polling notices purely visual mat revisions');
assert.match(js,/window\.addEventListener\('storage'/,'Studio changes propagate to the match');
assert.match(js,/function encodeMat/,'Client compresses its own image');
assert.match(style,/@media\(max-width:780px\)/,'Mobile mats remain supported');
console.log('PASS Online playmat sharing and Cube owner-only permissions: Supabase verification, player/spectator authorization, normal duel compatibility');
