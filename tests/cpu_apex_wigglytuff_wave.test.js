'use strict';
const assert=require('node:assert/strict');
const {CATALOG}=require('../headless_duel');
const {score,configuration,knockoutChance}=require('../cpu_policy');
const wiggly=CATALOG.get('base2-16');
assert.equal(wiggly?.name,'Wigglytuff');
const machop=[...CATALOG.values()].find(c=>c.name==='Machop'&&Number(c.hp)===50);
assert.ok(machop,'50 HP Machop must exist');
const active={id:'base2-16',energies:[],damage:0,status:null};
const defender={id:machop.id,energies:[],damage:0,status:null};
const o={self:{active,bench:Array.from({length:4},()=>({id:machop.id})),hand:[],deckCount:30},opponent:{active:defender,bench:[]}};
const cfg=configuration({level:8});
const lullaby={type:'attack',payload:{attackIndex:0}};
const wave={type:'attack',payload:{attackIndex:1}};
assert.equal(knockoutChance(wiggly.attacks[1],active,defender,4),1);
assert.equal(knockoutChance(wiggly.attacks[1],active,defender,0),0);
assert.ok(score(wave,o,cfg,{})>score(lullaby,o,cfg,{}),'Apex must prefer Do the Wave knockout over Lullaby');
o.self.bench=[];
assert.ok(score(wave,o,cfg,{})<score(lullaby,o,cfg,{}),'without Bench, Lullaby remains strategically useful');
console.log('Wigglytuff Do the Wave Apex knockout scoring: passed');
