'use strict';
const assert=require('node:assert/strict');
const {makeDecision,validateAnswer,decisionForViewer}=require('./decision_core');
const {publicView}=require('./duel_protocol');
const {RoomCoordinator}=require('./duel_rooms');
const d=makeDecision({id:'trainer:91:2',actor:1,label:'Select two cards',options:[{id:'x',label:'Private X'},{id:'y',label:'Private Y'},{id:'z',label:'Private Z'}],min:2,max:2});
assert.deepEqual(validateAnswer(d,1,{decisionId:d.id,selected:['y','x']}).selected,['y','x']);
for(const bad of [{decisionId:d.id,selected:['x']},{decisionId:d.id,selected:['x','x']},{decisionId:d.id,selected:['x','unknown']},{decisionId:'old',selected:['x','y']},{decisionId:d.id,decline:true}])assert.throws(()=>validateAnswer(d,1,bad));
assert.throws(()=>validateAnswer(d,0,{decisionId:d.id,selected:['x','y']}));
assert.deepEqual(decisionForViewer(d,0),{id:d.id,waitingFor:1});
assert.equal(decisionForViewer(d,1).options[0].label,'Private X');
const newGame=()=>({turn:0,phase:'play',players:[{name:'A',hand:['secret'],deck:[],prizes:['prize'],bench:[]},{name:'B',hand:['other'],deck:[],prizes:[],bench:[]}],pendingDecision:d});
assert.equal(publicView(newGame(),0).pendingDecision.options,undefined);
assert.equal(publicView(newGame(),1).pendingDecision.options.length,3);
const rooms=new RoomCoordinator({createGame:newGame,applyCommand:(g,side,command)=>{if(command.type!=='choose')return {ok:false};g.pendingDecision=null;return {ok:true};}});
const host=rooms.create(),guest=rooms.join(host.code);rooms.start(host.code,host.token,{});
assert.throws(()=>rooms.dispatch(host.code,host.token,{type:'choose',payload:{decisionId:d.id,selected:['x','y']}},1),/another player/);
assert.throws(()=>rooms.dispatch(host.code,guest.token,{type:'choose',payload:{decisionId:d.id,selected:['x']}},1),/number/);
assert.throws(()=>rooms.dispatch(host.code,guest.token,{type:'end_turn'},1),/decision/);
assert.equal(rooms.dispatch(host.code,guest.token,{type:'choose',payload:{decisionId:d.id,selected:['x','y']}},1).revision,2);
assert.throws(()=>rooms.dispatch(host.code,guest.token,{type:'choose',payload:{decisionId:d.id,selected:['x','y']}},2),/No pending decision/);
console.log('Decision core: choices, privacy, ownership, bounds, and room validation pass.');
