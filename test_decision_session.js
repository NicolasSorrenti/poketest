'use strict';
const assert=require('node:assert/strict');
const {createSession}=require('./decision_session');
const session=createSession({actor:1,kind:'pokemon-target',options:[{id:'bench:0'},{id:'bench:1'}]});
const reply={decisionId:session.decision.id,selected:['bench:0']};
let calls=0;
assert.throws(()=>session.answer(0,reply,[{id:'bench:0'}],()=>++calls),/another player/);
assert.throws(()=>session.answer(1,reply,[{id:'bench:1'}],()=>++calls),/no longer legal/);
assert.equal(calls,0);
assert.equal(session.answer(1,reply,[{id:'bench:0'}],()=>false),false);
assert.equal(session.status,'pending');
assert.equal(session.answer(1,reply,[{id:'bench:0'}],()=>++calls),1);
assert.equal(session.status,'resolved');
assert.throws(()=>session.answer(1,reply,[{id:'bench:0'}],()=>++calls),/no longer available/);
const cancelled=createSession({actor:0,options:[{id:'x'}]});
assert.equal(cancelled.cancel(),true);assert.equal(cancelled.cancel(),false);
assert.throws(()=>cancelled.answer(0,{decisionId:cancelled.decision.id,selected:['x']},[{id:'x'}],()=>1),/no longer available/);
console.log('PASS: shared decision sessions support actor authorization, legal-option refresh, retry, cancel, and single-commit lifecycle');
const legacy=require('./legacy_choice_bridge');
const pick={options:[{index:1,name:'A'},{index:2,name:'B'}]};
let commits=0;
const oldExecute=v=>{commits++;return v;};
legacy.prepare(pick,0);
assert.equal(legacy.commit(pick,0,1,oldExecute),1);
assert.equal(commits,1);
assert.equal(legacy.cancel(pick),false);
const target=require('./target_choice_bridge');
const targetReq={name:'Target'};
const legal=[{side:1,slot:-1}];
target.prepare(targetReq,legal,0);
assert.equal(target.commit(targetReq,0,1,-1,legal,()=>true),true);
assert.throws(()=>target.commit(targetReq,0,1,-1,legal,()=>true),/no longer available/);
