assert.equal(element.textContent,'','No replay of old events upon joining the match');
feedback.update(mk(2,0,20,0,null,['Grimer takes 20 damage.']),0);
assert.equal(feedback.unitClass(0,-1),'card-hit');
assert.equal(element.textContent,'Grimer takes 20 damage.');
feedback.update(mk(3,0,20,1,null,['Grimer attaches Grass Energy.']),0);
assert.equal(feedback.unitClass(0,-1),'card-powered');
feedback.update(mk(4,1,20,1,null,['Guest’s turn.']),0);
assert.equal(element.textContent,'OPPONENT TURN');
assert.ok(classes.has('turn-change'));
feedback.update(mk(5,0,20,1,{id:'choose:1',actor:0},['Choose attack target.']),0);
assert.equal(element.textContent,'YOUR TURN');
feedback.update(mk(6,0,20,1,{id:'choose:2',actor:0},['Choose your Energy.']),0);
assert.equal(element.textContent,'YOUR DECISION');
feedback.reset();assert.equal(element.textContent,'');
assert.equal(classes.has('show'),false);
