'use strict';
const assert=require('node:assert/strict');
const {makeDuelFeedback,energyStack}=require('./duel_quick_ui');
const classes=new Set();
const element={textContent:'',offsetWidth:250,classList:{add:(...x)=>x.forEach(y=>classes.add(y)),remove:(...x)=>x.forEach(y=>classes.delete(y)),contains:x=>classes.has(x)}};
const feedback=makeDuelFeedback(element);
const mk=(revision,turn,damage,attached,pending=null,messages=[])=>({revision,view:{phase:'game',turn,round:1,messages,pendingDecision:pending,players:[{active:{id:'base3-48',damage,energies:Array(attached).fill('base1-99')},bench:[]},{active:{id:'gym2-43',damage:0,energies:[]},bench:[]}]}});
