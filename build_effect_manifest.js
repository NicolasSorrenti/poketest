'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const sets=['base1','base2','base3','base4','base5','gym1','gym2','neo1','neo2','neo3','neo4','basep'];
const present=sets.filter(s=>fs.existsSync(path.join(__dirname,'cards',s+'.json')));
const {applyCardCorrections}=require('./card_corrections');
const cards=applyCardCorrections(present.flatMap(s=>JSON.parse(fs.readFileSync(path.join(__dirname,'cards',s+'.json'),'utf8'))));
const src=fs.readFileSync(path.join(__dirname,'engine.js'),'utf8');
const prefix=src.split('async function load()')[0].replace('const engine=new Engine();window.NeoCampus={engine,get cards(){return cards},lookup};','const engine=new Engine();');
const el=()=>({classList:{add(){},remove(){}},textContent:'',style:{}});
const ctx={console,Math,document:{getElementById:el,querySelector:()=>null},setTimeout(){},clearTimeout(){}};
vm.createContext(ctx);vm.runInContext(prefix,ctx);ctx.input=cards;
const attacks=vm.runInContext('cards=input;engine.attackAudit()',ctx);
const powers=vm.runInContext('engine.powerAudit()',ctx);
const categorise=text=>{
 const t=(text||'').toLowerCase();
 if(/search your deck|look at (?:the|top).*cards/.test(t))return 'search-and-deck';
 if(/energy|discard .*attached/.test(t))return 'energy-manipulation';
 if(/damage counter|heal|remove .*damage/.test(t))return 'damage-and-healing';
 if(/bench|switch|active pok[eé]mon|retreat/.test(t))return 'field-movement-and-targeting';
 if(/opponent.s next turn|prevent|reduce|isn.t affected/.test(t))return 'lingering-and-protection';
 if(/flip|heads|tails/.test(t))return 'coin-and-random';
 if(/asleep|paralyz|confus|poison|burned/.test(t))return 'status-conditions';
 if(/draw |hand/.test(t))return 'draw-and-hand';
 if(/attack|damage/.test(t))return 'attack-and-damage';
 return 'individual-scripting';
};
const rows=[...attacks.map(x=>({...x,kind:'attack',family:categorise(x.text)})),...powers.map(x=>({...x,kind:'power',family:categorise(x.text)}))];
const missing=rows.filter(x=>!x.implemented);
const groups={};for(const r of missing)(groups[r.family]??=[]).push({id:r.card,name:r.cardName,effect:r.attack||r.name,text:r.text,kind:r.kind});
const summary={dataSource:'TCGdex (normalized local cache)',expectedSets:sets,loadedSets:present,missingSets:sets.filter(x=>!present.includes(x)),cards:cards.length,attacks:{total:attacks.length,recognized:attacks.filter(x=>x.implemented).length,unimplemented:attacks.filter(x=>!x.implemented).length},powers:{total:powers.length,recognized:powers.filter(x=>x.implemented).length,unimplemented:powers.filter(x=>!x.implemented).length},warning:'Recognized patterns are not proof of rules completeness; individual interactions still require regression tests.'};
fs.writeFileSync(path.join(__dirname,'effect_manifest.json'),JSON.stringify({summary,missingByFamily:groups,all:rows},null,2));
console.log(JSON.stringify(summary,null,2));
if(!present.length)console.warn('No cached card database. Run npm run cards first; do not interpret zero effects as full coverage.');
