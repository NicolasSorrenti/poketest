'use strict';
const assert=require('node:assert/strict');
const {CubeService}=require('./cube_service');
const {ClassicLocalService}=require('./classic_local_service');
const {CATALOG,createGame}=require('./headless_duel');
const {isBasicPokemon}=require('./core_rules');
const C=require('./cube_draft');
const cubes=new CubeService(),classic=new ClassicLocalService({maxSessions:8});
let state=cubes.create({seed:475}),token=state.token;
assert.equal(state.started,false);
assert.throws(()=>cubes.start(token,[],state.revision,classic),/Draft must be completed/);
for(let i=0;i<60;i++){
 assert.equal(state.drafted.length,i);
 state=cubes.pick(token,state.pack[0].id,state.revision);
}
assert.equal(state.done,true);
assert.equal(state.suggestedDeck.length,40);
const eligibility=C.validateBuild(state.drafted.map(c=>c.id),state.suggestedDeck);
assert.deepEqual(eligibility,{valid:true});
assert.equal(state.energyIds.Water!==undefined,true);
const poisoned=[...state.suggestedDeck];poisoned[0]='invalid-id';
assert.throws(()=>cubes.start(token,poisoned,state.revision,classic),/Unknown card|not drafted/);
const launched=cubes.start(token,state.suggestedDeck,state.revision,classic);
assert.equal(typeof launched.duelToken,'string');
assert.throws(()=>cubes.start(token,state.suggestedDeck,state.revision,classic),/Stale draft revision|already started/);
const duel=classic.state(launched.duelToken);
assert.equal(duel.format,'online-preview');
assert.deepEqual(duel.counts,[40,40]);
assert.equal(classic.session(launched.duelToken).game.deckSize,40);
assert.equal(classic.session(launched.duelToken).game.prizeCount,4);
const hand=duel.view.players[0].hand;
const basic=hand.findIndex(id=>isBasicPokemon(CATALOG.get(id)));
assert(basic>=0,'40-card player deck has an opening Basic');
let result=classic.action(launched.duelToken,{type:'setup_select',payload:{handIndex:basic}},duel.revision);
result=classic.action(launched.duelToken,{type:'setup_confirm',payload:{}},result.revision);
assert.equal(result.view.phase,'game');
assert.deepEqual(result.counts,[40,40]);
assert.equal(result.view.players[0].prizeCount,4);
assert.equal(result.view.players[1].prizeCount,4);
const classicDeck=require('./retail_theme_decks').list('bodyguard');
const oldGame=createGame({decks:[classicDeck,classicDeck],format:'classic',seed:5});
assert.equal(oldGame.deckSize,60);
assert.equal(oldGame.prizeCount,6);
assert.throws(()=>createGame({decks:[classicDeck,classicDeck],format:'classic',deckSize:40,prizeCount:4}),/Unsupported deck/);
console.log('PASS Cube 40-card match: 4 Prize cards, real CPU match setup, preserved 60-card rules');
