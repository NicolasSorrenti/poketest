'use strict';
const assert=require('node:assert/strict');
const {prepare,commit}=require('./legacy_choice_bridge');
let effect=0;
const req={label:'Choose two Energy cards',multi:true,min:2,max:2,options:[{index:4,name:'Water'},{index:7,name:'Fire'},{index:9,name:'Grass'}]};
const d=prepare(req,0).decision;
assert.equal(d.options.length,3);
assert.equal(prepare(req,0).decision.id,d.id);
assert.throws(()=>commit(req,1,[4,7],()=>effect++),/another player/);
assert.throws(()=>commit(req,0,[4],()=>effect++),/number/);
assert.throws(()=>commit(req,0,[4,4],()=>effect++),/no longer available/);
assert.throws(()=>commit(req,0,[4,55],()=>effect++),/no longer available/);
assert.equal(effect,0);
assert.deepEqual(commit(req,0,[7,4],v=>{effect++;return v;}),[7,4]);
assert.equal(effect,1);
const single={options:[{index:-1,name:'Active'},{index:0,name:'Bench'}]};
assert.equal(commit(single,0,-1,v=>v),-1);
assert.throws(()=>commit(single,0,[0,-1],v=>v),/number/);
console.log('PASS: legacy picker choices use shared decision validation before executing effects');
